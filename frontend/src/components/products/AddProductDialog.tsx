import { useState, useEffect } from 'react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select';
import { createProduct, Product } from '@/api/products';
import { getCategories, Category } from '@/api/categories';
import { useToast } from '@/hooks/use-toast';

interface AddProductDialogProps {
  isOpen: boolean;
  onOpenChange: (isOpen: boolean) => void;
  onSave: (product: Product) => void;
  categories?: Category[]; // Optional: if provided, use these instead of fetching
}

export const AddProductDialog = ({
  isOpen,
  onOpenChange,
  onSave,
  categories: providedCategories,
}: AddProductDialogProps) => {
  const { toast } = useToast();
  const [loading, setLoading] = useState(false);
  const [categories, setCategories] = useState<Category[]>(providedCategories || []);
  const [loadingCategories, setLoadingCategories] = useState(false);
  const [formData, setFormData] = useState({
    name: '',
    categoryId: '',
    minStock: '0',
    lastPurchasePrice: '0',
    salePrice: '0',
    quantity: '0',
    tvaPercent: '0',
  });

  // Update categories when providedCategories change
  useEffect(() => {
    if (providedCategories) {
      setCategories(providedCategories);
      // Set default category if available
      if (providedCategories.length > 0 && !formData.categoryId) {
        setFormData(prev => ({ ...prev, categoryId: providedCategories[0].id }));
      }
    }
  }, [providedCategories]);

  useEffect(() => {
    if (isOpen) {
      // Only fetch if categories not provided
      if (!providedCategories || providedCategories.length === 0) {
        loadCategories();
      } else {
        // Use provided categories and set default
        if (providedCategories.length > 0 && !formData.categoryId) {
          setFormData(prev => ({ ...prev, categoryId: providedCategories[0].id }));
        }
      }
    } else {
      // Reset form when dialog closes
      const firstCategoryId = categories.length > 0 ? categories[0].id : '';
      setFormData({
        name: '',
        categoryId: firstCategoryId,
        minStock: '0',
        lastPurchasePrice: '0',
        salePrice: '0',
        quantity: '0',
        tvaPercent: '0',
      });
    }
  }, [isOpen, providedCategories]);

  const loadCategories = async () => {
    try {
      setLoadingCategories(true);
      const data = await getCategories({ limit: 200 }); // Max allowed by backend
      const categoriesList = Array.isArray(data) ? data : [];
      setCategories(categoriesList);
      // Set default category if available and not already set
      if (categoriesList.length > 0 && !formData.categoryId) {
        setFormData(prev => {
          // Only set if not already set
          if (!prev.categoryId) {
            return { ...prev, categoryId: categoriesList[0].id };
          }
          return prev;
        });
      }
    } catch (err: any) {
      console.error('Error loading categories:', err);
      toast({
        title: 'Erreur',
        description: 'Impossible de charger les catégories',
        variant: 'destructive',
      });
    } finally {
      setLoadingCategories(false);
    }
  };

  const handleSubmit = async () => {
    if (!formData.name.trim()) {
      toast({
        title: 'Erreur',
        description: 'Le nom est requis',
        variant: 'destructive',
      });
      return;
    }

    if (!formData.categoryId) {
      toast({
        title: 'Erreur',
        description: 'Veuillez sélectionner une catégorie',
        variant: 'destructive',
      });
      return;
    }

    try {
      setLoading(true);
      const product = await createProduct({
        // Code will be auto-generated by backend
        name: formData.name.trim(),
        categoryId: formData.categoryId,
        minStock: Number(formData.minStock) || 0,
        lastPurchasePrice: Number(formData.lastPurchasePrice) || 0,
        salePrice: Number(formData.salePrice) || 0,
        quantity: Number(formData.quantity) || 0,
        tvaPercent: Number(formData.tvaPercent) || 0,
      });
      onSave(product);
      toast({
        title: 'Produit créé avec succès',
        description: `Code généré: ${product.code}`
      });
      // Reset form
      const firstCategoryId = categories.length > 0 ? categories[0].id : '';
      setFormData({
        name: '',
        categoryId: firstCategoryId,
        minStock: '0',
        lastPurchasePrice: '0',
        salePrice: '0',
        quantity: '0',
        tvaPercent: '0',
      });
      onOpenChange(false);
    } catch (err: any) {
      toast({
        title: 'Erreur',
        description: err.response?.data?.message || 'Erreur lors de la création',
        variant: 'destructive',
      });
    } finally {
      setLoading(false);
    }
  };

  return (
    <Dialog open={isOpen} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-md">
        <DialogHeader>
          <DialogTitle>Nouveau Produit</DialogTitle>
          <DialogDescription>
            Créez rapidement un nouveau produit
          </DialogDescription>
        </DialogHeader>
        <div className="space-y-4 py-4">
          <div>
            <Label htmlFor="newProductName">Nom *</Label>
            <Input
              id="newProductName"
              value={formData.name}
              onChange={(e) =>
                setFormData({ ...formData, name: e.target.value })
              }
              required
            />
            <p className="text-xs text-muted-foreground mt-1">
              Le code sera généré automatiquement (format: p-XXXX)
            </p>
          </div>
          <div>
            <Label htmlFor="newProductCategory">Catégorie *</Label>
            <Select
              value={formData.categoryId || undefined}
              onValueChange={(value) =>
                setFormData({ ...formData, categoryId: value })
              }
              disabled={loadingCategories || categories.length === 0}
              required
            >
              <SelectTrigger id="newProductCategory">
                <SelectValue placeholder={loadingCategories ? "Chargement..." : categories.length === 0 ? "Aucune catégorie - Créez-en une d'abord" : "Sélectionner une catégorie"} />
              </SelectTrigger>
              <SelectContent>
                {categories.length > 0 ? (
                  categories.map((category) => (
                    <SelectItem key={category.id} value={category.id}>
                      {category.name}
                    </SelectItem>
                  ))
                ) : (
                  <div className="px-2 py-1.5 text-sm text-muted-foreground">
                    Aucune catégorie disponible
                  </div>
                )}
              </SelectContent>
            </Select>
            {categories.length === 0 && !loadingCategories && (
              <p className="text-xs text-muted-foreground mt-1">
                Créez d'abord une catégorie dans le panneau "Gérer les catégories" ci-dessus
              </p>
            )}
          </div>
          <div className="grid grid-cols-2 gap-4">
            <div>
              <Label htmlFor="newProductQuantity">Quantité (Stock)</Label>
              <Input
                id="newProductQuantity"
                type="number"
                step="0.01"
                value={formData.quantity}
                onWheel={(e) => (e.target as HTMLInputElement).blur()}
                onChange={(e) =>
                  setFormData({ ...formData, quantity: e.target.value })
                }
              />
            </div>
            <div>
              <Label htmlFor="newProductMinStock">Stock Minimum</Label>
              <Input
                id="newProductMinStock"
                type="number"
                step="0.01"
                value={formData.minStock}
                onWheel={(e) => (e.target as HTMLInputElement).blur()}
                onChange={(e) =>
                  setFormData({ ...formData, minStock: e.target.value })
                }
              />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-4">
            <div>
              <Label htmlFor="newProductSalePrice">Prix de Vente TTC</Label>
              <Input
                id="newProductSalePrice"
                type="number"
                step="0.01"
                value={formData.salePrice}
                onWheel={(e) => (e.target as HTMLInputElement).blur()}
                onChange={(e) =>
                  setFormData({ ...formData, salePrice: e.target.value })
                }
              />
            </div>
            <div>
              <Label htmlFor="newProductLastPurchasePrice">Dernier Prix d'Achat</Label>
              <Input
                id="newProductLastPurchasePrice"
                type="number"
                step="0.01"
                value={formData.lastPurchasePrice}
                onWheel={(e) => (e.target as HTMLInputElement).blur()}
                onChange={(e) =>
                  setFormData({ ...formData, lastPurchasePrice: e.target.value })
                }
              />
            </div>
          </div>

          <div>
            <Label htmlFor="newProductTvaPercent">TVA (%)</Label>
            <Input
              id="newProductTvaPercent"
              type="number"
              step="0.01"
              min="0"
              max="100"
              value={formData.tvaPercent}
              onWheel={(e) => (e.target as HTMLInputElement).blur()}
              onChange={(e) =>
                setFormData({ ...formData, tvaPercent: e.target.value })
              }
              placeholder="Ex: 0, 1, 2, 10, 20, etc."
            />
          </div>
        </div>
        <DialogFooter>
          <Button
            type="button"
            variant="outline"
            onClick={() => onOpenChange(false)}
          >
            Annuler
          </Button>
          <Button type="button" onClick={handleSubmit} disabled={loading}>
            {loading ? 'Création...' : 'Créer'}
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
};

